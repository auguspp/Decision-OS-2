"""Compact derived news snapshots in the SAME SourceInput store.

The only aggregation is news_rolling._assemble_news. Stored snapshots hold exact
source references and the complete logical-view digest, not a second news pool.
Reading replays those immutable batches before paging; missing data is not empty.
"""
from __future__ import annotations

from copy import deepcopy
import re

from decision_kernel.domain.records import digest, encoded, require
from decision_kernel.application import news_rolling as roll

SCHEMA = "dos2-news-rolling-index-v1"
MAX_REPLAY_BYTES = 8 * 1024 * 1024
REPRESENTATION = "EXACT_SOURCE_REFERENCES_WITH_LOGICAL_VIEW_DIGEST"
FIELDS = {"schema", "window_hours", "as_of", "window_start", "meaning", "interval",
          "predecessor", "batch_references", "rejected_references", "source_outcomes",
          "losses", "count_meaning", "coverage", "entry_count", "entries_sha256",
          "logical_sha256", "representation", "index_sha256"}


def _index(logical):
    value = deepcopy({k: v for k, v in logical.items() if k not in ("entries", "rolling_sha256")})
    value.update(schema=SCHEMA, entry_count=len(logical["entries"]),
                 entries_sha256=digest(encoded(logical["entries"])),
                 logical_sha256=logical["rolling_sha256"], representation=REPRESENTATION)
    value["index_sha256"] = digest(encoded(value))
    return value


def verify_index(value):
    require(isinstance(value, dict) and set(value) == FIELDS and value["schema"] == SCHEMA
            and value["representation"] == REPRESENTATION, "NEWS_INDEX_SHAPE")
    original = {k: v for k, v in value.items() if k != "index_sha256"}
    require(value["index_sha256"] == digest(encoded(original))
            and len(encoded(value)) <= roll.MAX_BYTES, "NEWS_INDEX_DIGEST_OR_SIZE")
    require(type(value["entry_count"]) is int and 0 <= value["entry_count"] <= roll.MAX_OBSERVATIONS
            and all(isinstance(value[k], str) and re.fullmatch(r"[0-9a-f]{64}", value[k])
                    for k in ("entries_sha256", "logical_sha256")), "NEWS_INDEX_ENTRY_COMMITMENT")
    # Reuse all existing clock/reference/health/loss/authority validation. This
    # empty probe validates headers only, not the declared entries or coverage.
    probe = deepcopy({k: v for k, v in value.items() if k not in
                      {"entry_count", "entries_sha256", "logical_sha256", "representation", "index_sha256"}})
    probe.update(schema=roll.SCHEMA, entries=[])
    roll.verify_rolling(roll._seal(probe))
    coverage = value["coverage"]
    require(isinstance(coverage, dict) and set(coverage) == set(probe["coverage"]), "NEWS_INDEX_COVERAGE")
    expected = dict(probe["coverage"])
    expected["retained_versions"] = value["entry_count"]
    gap = coverage.get("maximum_observation_gap_seconds")
    require(type(gap) in (int, float) and 0 <= gap <= 24 * 3600, "NEWS_INDEX_COVERAGE")
    expected["maximum_observation_gap_seconds"] = gap
    require(coverage == expected, "NEWS_INDEX_COVERAGE")
    return value


def rolling_index(reader, references, *, as_of, predecessor=None):
    """Do not inline or crop article rows to fit the persistent snapshot budget."""
    logical = roll._seal(roll._assemble_news(reader, references, as_of=as_of, predecessor=predecessor))
    roll._verify_rolling(logical, max_bytes=MAX_REPLAY_BYTES)
    return verify_index(_index(logical))


def restore_index(reader, value):
    """Rebuild all selected batches; refuse a missing/changed source or bad digest."""
    verify_index(value)
    logical = roll._assemble_news(reader, value["batch_references"], as_of=value["as_of"], _replay=True)
    require(not logical["rejected_references"] and logical["batch_references"] == value["batch_references"],
            "NEWS_INDEX_SOURCE_RESTORE_FAILED")
    # These are historical window metadata, not new events generated by reading.
    # The exact complete digest below binds them together with rebuilt entries.
    for key in ("predecessor", "losses", "rejected_references"):
        logical[key] = deepcopy(value[key])
    roll._seal(logical)
    roll._verify_rolling(logical, max_bytes=MAX_REPLAY_BYTES)
    require(_index(logical) == value, "NEWS_INDEX_LOGICAL_REPLAY_MISMATCH")
    return logical


def read_index(reader, value, *, source=None, query="", limit=40, cursor=None):
    logical = restore_index(reader, value)
    return {**roll._page_rolling(logical, source=source, query=query, limit=limit, cursor=cursor),
            "snapshot_schema": SCHEMA, "index_sha256": value["index_sha256"],
            "source_reconstruction": "verified-exact-selected-batches"}


def open_index(reader, ref):
    return verify_index(roll._load(reader, roll.reference(ref)))
